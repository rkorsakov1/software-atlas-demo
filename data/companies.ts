  "As originally filed, on the pre-ASC 606 basis. Microsoft restated only FY2016 and FY2017 on adoption, so the step from FY2015 into FY2016 mixes two revenue-recognition bases: FY2016 was $85.320B as originally filed against the $91.154B restated figure shown here.";

