/**
 * Series pulled from the SEC companyfacts API in one pass (2026-09-24). Each fiscal
 * year uses the value from the most recent 10-K that reports it, so a later
 * restatement replaces the as-filed figure; the year is the one the fiscal year
 * ends in.
 */
const LATEST_FILED_NOTE =
  "Annual revenue from the most recent 10-K reporting this fiscal year (SEC XBRL), so later restatements replace the original filing. The year is the calendar year the fiscal year ends in.";

const revenue = (points: readonly YearValue[], sourceId: string = SEC_XBRL): DataPoint[] =>
  points.map(([year, value]) => ({
    value,
    year,
    unit: "USD_B",
    sourceId,
    confidence: "reported",
  }));

const margin = (points: readonly YearValue[], note: string = GROSS_MARGIN_NOTE): DataPoint[] =>
  points.map(([year, value]) => ({
    value,
    year,
    unit: "percent",
    sourceId: SEC_XBRL,
    confidence: "modeled",
    note,
  }));

const runRate = (
  year: number,
  value: number,
  low: number,
  high: number,
  sourceId: string,
): DataPoint => ({
  value,
  low,
  high,
  year,
  unit: "USD_B",
  sourceId,
  confidence: "estimated",
  note: RUN_RATE_NOTE,
});

