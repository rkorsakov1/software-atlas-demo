import type { DataPoint, Company } from "@/data/types";

/**
 * The company roster. Every id referenced by `eras.ts`, `events.ts`,
 * `emerging.ts`, `flows.ts` and `markets.ts` resolves here.
 *
 * Three rules govern the numbers, and they are stricter than they look:
 *
 * 1. `revenueByYear` carries only figures the verification pass actually read
 *    (`docs/verification-log.md` §1). Most companies here have no verified
 *    series, and they ship with an empty array rather than an invented one. A
 *    company without revenue is a first-class participant: it still carries an
 *    archetype, markets, moats, status and lineage.
 * 2. `marketCapByYear` is omitted everywhere. No citable series exists — share
 *    price is not in SEC XBRL — so the field stays absent rather than modelled
 *    (ruling `docs/CONTRACTS.md` §8.5).
 * 3. `grossMarginByYear` is always `modeled`: both inputs are as-filed, but the
 *    ratio is this project's derivation (verification-log §9, ruling §8.9).
 *
 * `moats` are modeled judgments scored against `data/rubric.ts`; `moatRationale`
 * gives one sentence per non-zero score so the judgment can be argued with.
 *
 * Two conventions worth knowing: SAP ships with an empty `revenueByYear` because
 * it reports in EUR and the `Unit` enum has no EUR member (ruling §8.6/§8.10),
 * while keeping its currency-neutral margin series; and a company acquired by a
 * firm that is not itself in the Atlas (AOL, Borland, Compaq, Data General,
 * Novell) carries `status: "acquired"` with no `acquiredById`, rather than a
 * dangling id.
 */

type YearValue = readonly [year: number, value: number];

/** SEC XBRL `companyconcept` API — the as-filed revenue and cost facts. */
const SEC_XBRL = "S28";

const GROSS_MARGIN_NOTE = "Modeled: 1 − cost of revenue ÷ revenue, both as filed.";

const RUN_RATE_NOTE =
  "Annualised run rate as reported by press; not GAAP revenue. The low/high band reflects the rounding in the reported figure.";

/**
 * Annotates a series that crosses a basis break, so a chart deriving
 * year-over-year growth from it cannot silently present a divestiture as organic
 * decline. A `note` on a `reported` point is allowed: only `modeled` points
 * require one.
 */
const onBasis = (points: readonly DataPoint[], note: string): DataPoint[] =>
  points.map((point) => ({ ...point, note }));

